#!/usr/bin/env python3
"""Lycoles v33: generate bounded read-only Roblox diagnostics from reviewed specs.

Never copies or executes source corpus code. Never invokes game remotes.
The output is a real GUI with working inspection buttons and cleanup.
"""
import argparse
import json
import pathlib
import re

VERSION="33.0"
MAX_FEATURES=100
IDENT=re.compile(r"^[A-Za-z_][A-Za-z0-9_]{0,63}$")
PATH=re.compile(r"^(?:game|workspace|Workspace|ReplicatedStorage|Players|PlayerGui)(?:\.[A-Za-z_][A-Za-z0-9_]*){0,12}$")
ALLOWED={"read_object_presence","read_local_player","read_character","read_player_gui"}
def validate(spec):
    if not isinstance(spec,dict) or spec.get("schemaVersion")!=VERSION:raise ValueError("Expected v33 reviewed specification")
    place=spec.get("placeId")
    if type(place) is not int or place<=0:raise ValueError("Positive numeric placeId required")
    features=spec.get("features")
    if not isinstance(features,list) or not 1<=len(features)<=MAX_FEATURES:raise ValueError("1-100 features required")
    ids=set()
    for f in features:
        if not isinstance(f,dict) or f.get("reviewed") is not True:raise ValueError("Every feature must be explicitly reviewed")
        name=f.get("name");action=f.get("action")
        if not isinstance(name,str) or not IDENT.fullmatch(name):raise ValueError("Invalid feature name")
        if name in ids:raise ValueError("Duplicate feature name")
        ids.add(name)
        if action not in ALLOWED:raise ValueError("Unsupported or unsafe action")
        paths=f.get("paths",[])
        if not isinstance(paths,list) or len(paths)>20:raise ValueError("Invalid path list")
        if action=="read_object_presence" and not paths:raise ValueError("Presence action requires paths")
        if any(not isinstance(p,str) or not PATH.fullmatch(p) for p in paths):raise ValueError("Invalid object path")
    return spec
def quote(s):
    return json.dumps(s,ensure_ascii=True)
def generate(spec):
    validate(spec)
    place=spec["placeId"]
    entries=[]
    for f in spec["features"]:
        entries.append("    {name="+quote(f["name"])+", action="+quote(f["action"])+", paths={"+
                       ",".join(quote(p) for p in f.get("paths",[]))+"}},")
    template='''-- Generated by Lycoles v33. Reviewed read-only diagnostic GUI.
-- Execution is NOT proof of server-side gameplay outcomes.
local Players=game:GetService("Players")
local player=Players.LocalPlayer
assert(game.PlaceId == __PLACE__, "This diagnostic is for a different place")
assert(player, "LocalPlayer missing")
if type(_G.LycolesGeneratedClose)=="function" then pcall(_G.LycolesGeneratedClose) end
local alive=true
local gui=Instance.new("ScreenGui")
gui.Name="LycolesDiagnosticV33"
gui.ResetOnSpawn=false
gui.Parent=player:WaitForChild("PlayerGui")
local frame=Instance.new("Frame")
frame.Name="Panel"
frame.Size=UDim2.fromOffset(390,360)
frame.Position=UDim2.new(0,30,0.15,0)
frame.BackgroundColor3=Color3.fromRGB(30,35,45)
frame.Parent=gui
local layout=Instance.new("UIListLayout")
layout.Padding=UDim.new(0,5)
layout.Parent=frame
local function button(name,callback)
    local b=Instance.new("TextButton")
    b.Size=UDim2.new(1,0,0,34)
    b.BackgroundColor3=Color3.fromRGB(60,75,95)
    b.TextColor3=Color3.new(1,1,1)
    b.Text=name
    b.TextScaled=false
    b.TextSize=15
    b.Parent=frame
    b.Activated:Connect(function()
        if not alive then return end
        local ok,err=pcall(callback)
        if not ok then warn("[Lycoles] "..tostring(err)) end
    end)
    return b
end
local output=Instance.new("TextLabel")
output.Name="Result"
output.Size=UDim2.new(1,0,0,65)
output.BackgroundTransparency=1
output.TextColor3=Color3.new(1,1,1)
output.TextWrapped=true
output.TextSize=14
output.Text="Select a diagnostic."
output.Parent=frame
local function show(s)
    if alive then output.Text=tostring(s):sub(1,400) end
end
local function resolve(path)
    local parts=string.split(path,".")
    local root=table.remove(parts,1)
    local node
    if root=="game" then node=game
    elseif root=="workspace" or root=="Workspace" then node=workspace
    elseif root=="PlayerGui" then node=player:FindFirstChildOfClass("PlayerGui")
    else node=game:GetService(root) end
    for _,part in ipairs(parts) do
        if not node then return nil end
        node=node:FindFirstChild(part)
    end
    return node
end
local features={
__FEATURES__
}
for _,f in ipairs(features) do
    button(f.name,function()
        if f.action=="read_object_presence" then
            local found=0
            for _,path in ipairs(f.paths) do
                if resolve(path) then found=found+1 end
            end
            show(f.name..": "..found.."/"..#f.paths.." objects visible")
        elseif f.action=="read_local_player" then
            show("Player: "..player.Name.." | UserId: "..tostring(player.UserId))
        elseif f.action=="read_character" then
            local character=player.Character
            local humanoid=character and character:FindFirstChildOfClass("Humanoid")
            show("Character: "..(character and character.Name or "missing")..
                 " | Humanoid: "..(humanoid and "present" or "missing"))
        elseif f.action=="read_player_gui" then
            local pg=player:FindFirstChildOfClass("PlayerGui")
            show("PlayerGui: "..(pg and tostring(#pg:GetChildren()).." direct children" or "missing"))
        end
    end)
end
local function close()
    if not alive then return end
    alive=false
    if gui then gui:Destroy() end
    if _G.LycolesGeneratedClose==close then _G.LycolesGeneratedClose=nil end
end
_G.LycolesGeneratedClose=close
button("Close",close)
'''
    return template.replace("__PLACE__",str(place)).replace("__FEATURES__","\n".join(entries))
def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("reviewed_spec",type=pathlib.Path)
    p.add_argument("--output",type=pathlib.Path,default=pathlib.Path("build/LycolesDiagnosticV33.lua"))
    a=p.parse_args()
    spec=json.loads(a.reviewed_spec.read_text(encoding="utf-8"))
    lua=generate(spec)
    a.output.parent.mkdir(parents=True,exist_ok=True)
    a.output.write_text(lua,encoding="utf-8")
    print("Generated",len(spec["features"]),"reviewed diagnostic actions:",a.output)
    print("STATIC GENERATION ONLY: no live gameplay verification performed")
if __name__=="__main__":main()
